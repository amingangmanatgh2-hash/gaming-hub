  function search(query, limit) {
    var q = String(query || '').trim();
    if (!q) return [];
    var scored = [];
    KB.forEach(function (entry) {
      var score = 0;
      entry.keywords.forEach(function (k) {
        if (q.indexOf(k) >= 0) score += k.length >= 3 ? 3 : 2;
        if (k.indexOf(q) === 0) score += 2;
      });
      if (entry.title.indexOf(q) >= 0) score += 2;
      if (entry.text.indexOf(q) >= 0) score += 1;
      if (score > 0) scored.push({ entry: entry, score: score });
    });
    scored.sort(function (a, b) { return b.score - a.score; });
    return scored.slice(0, limit || 3).map(function (x) { return x.entry; });
  }

  function get(id) {
    for (var i = 0; i < KB.length; i++) if (KB[i].id === id) return KB[i];
    return null;
  }

  global.AMIN = global.AMIN || {};
  global.AMIN.knowledge = { KB: KB, search: search, get: get };
