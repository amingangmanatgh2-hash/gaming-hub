const FA = '۰۱۲۳۴۵۶۷۸۹';
export const faNum = (n) => String(n).replace(/\d/g, (d) => FA[+d]).replace(/-/g, '−').replace(/\./g, '/');

function hash(str) { let h = 2166136261; for (let i = 0; i < str.length; i++) { h ^= str.charCodeAt(i); h = Math.imul(h, 16777619); } return h >>> 0; }
function mulberry32(seed) {
  return () => {
    seed |= 0; seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rnd = (r, min, max) => min + Math.floor(r() * (max - min + 1));
const pick = (r, arr) => arr[Math.floor(r() * arr.length)];

/* ---------------- تمرین‌های محاسباتی ریاضی (با راه‌حل) ---------------- */
function mathDrills(grade, r, count = 8) {
  const out = [];
  const add = (q, a, x) => out.push({ q, a, x: x || '' });
  const f = faNum;
  for (let i = 0; i < count; i++) {
    const k = i % 4;
    if (grade === 1) {
      if (k === 0) { const a = rnd(r, 4, 15), b = rnd(r, 2, 9); add(`تمرین: حاصل ${f(a)} + ${f(b)} چند می‌شود؟`, `${f(a + b)}`, `از ${f(a)} به اندازهٔ ${f(b)} تا جلو بشمار.`); }
      else if (k === 1) { const a = rnd(r, 9, 20), b = rnd(r, 2, a - 2); add(`تمرین: حاصل ${f(a)} − ${f(b)} چند می‌شود؟`, `${f(a - b)}`, `از ${f(a)} به اندازهٔ ${f(b)} تا عقب بشمار.`); }
      else if (k === 2) { const a = rnd(r, 2, 9), step = pick(r, [1, 2, 5]); add(`تمرین: عدد بعدی را بگو: ${f(a)}، ${f(a + step)}، ${f(a + 2 * step)}، ...`, `${f(a + 3 * step)}`, `هر بار ${f(step)} تا اضافه شده است.`); }
      else { const a = rnd(r, 3, 18), b = rnd(r, 3, 18); if (a !== b) add(`تمرین: کدام عدد بزرگ‌تر است: ${f(a)} یا ${f(b)}؟`, `${f(Math.max(a, b))}`, 'در شمارش، عددی که دیرتر بیاید بزرگ‌تر است.'); }
    } else if (grade === 2) {
      if (k === 0) { const a = rnd(r, 24, 78), b = rnd(r, 13, 59); add(`تمرین: حاصل ${f(a)} + ${f(b)} را ستونی حساب کن.`, `${f(a + b)}`, 'یکان‌ها را جمع کن؛ اگر از ۹ بیشتر شد یکی به دهگان اضافه کن، بعد دهگان‌ها.'); }
      else if (k === 1) { const a = rnd(r, 45, 96), b = rnd(r, 12, a - 5); add(`تمرین: حاصل ${f(a)} − ${f(b)} چند است؟`, `${f(a - b)}`, 'اگر یکان کم آمد، از دهگان یکی قرض بگیر.'); }
      else if (k === 2) { const a = rnd(r, 11, 99); add(`تمرین: عدد ${f(a)} زوج است یا فرد؟ چرا؟`, a % 2 === 0 ? 'زوج است.' : 'فرد است.', 'به یکان نگاه کن: اگر ۰، ۲، ۴، ۶ یا ۸ باشد عدد زوج است.'); }
      else { const d = rnd(r, 2, 9), y = rnd(r, 0, 9); add(`تمرین: در عدد ${f(d * 10 + y)} ارزش رقم ${f(d)} چقدر است؟`, `${f(d * 10)}`, 'رقم دهگان یعنی چند بستهٔ ده‌تایی.'); }
    } else if (grade === 3 || grade === 4) {
      if (k === 0) { const a = rnd(r, 3, 9), b = rnd(r, 3, 9); add(`تمرین: حاصل ${f(a)} × ${f(b)} چند است؟`, `${f(a * b)}`, 'از جدول ضرب یا جمع تکراری استفاده کن.'); }
      else if (k === 1) { const b = rnd(r, 3, 9), q = rnd(r, 3, 12), a = b * q; add(`تمرین: حاصل ${f(a)} ÷ ${f(b)} چند است؟`, `${f(q)}`, `دنبال عددی بگرد که در ${f(b)} ضرب شود و ${f(a)} بدهد.`); }
      else if (k === 2 && grade === 4) { const d = pick(r, [6, 7, 8, 9, 10, 12]), p = rnd(r, 1, d - 1), q2 = rnd(r, 1, d - p - 1); add(`تمرین: حاصل  ${f(p)}/${f(d)} + ${f(q2)}/${f(d)}  چقدر است؟`, `${f(p + q2)}/${f(d)}`, 'در کسرهای هم‌مخرج فقط صورت‌ها جمع می‌شوند.'); }
      else if (k === 2) { const s = rnd(r, 4, 15); add(`تمرین: محیط مربعی به ضلع ${f(s)} سانتی‌متر چقدر است؟`, `${f(4 * s)} سانتی‌متر`, 'محیط مربع = ضلع × ۴'); }
      else { const a = rnd(r, 12, 48), b = rnd(r, 3, 9); add(`تمرین: حاصل ${f(a)} × ${f(b)} را پیدا کن.`, `${f(a * b)}`, `عدد را باز کن: (${f(Math.floor(a / 10) * 10)} × ${f(b)}) + (${f(a % 10)} × ${f(b)})`); }
    } else if (grade === 5 || grade === 6) {
      if (k === 0) { const p = pick(r, [10, 20, 25, 50]), base = rnd(r, 2, 12) * 20; add(`تمرین: ${f(p)} درصد از عدد ${f(base)} چقدر می‌شود؟`, `${f(base * p / 100)}`, `${f(p)}٪ یعنی ${f(p)} صدم عدد؛ عدد را در ${f(p)} ضرب و بر ۱۰۰ تقسیم کن.`); }
      else if (k === 1) { const a = rnd(r, 1, 8), b = rnd(r, 2, 9), c = rnd(r, 1, 9); add(`تمرین: کسر ${f(a)}/${f(b)} را در عدد ${f(c)} ضرب کن.`, `${f(a * c)}/${f(b)}${a * c >= b ? ' (قابل تبدیل به عدد مخلوط)' : ''}`, 'عدد صحیح در صورت ضرب می‌شود و مخرج ثابت می‌ماند.'); }
      else if (k === 2) { const a = rnd(r, 2, 20) - 10, b = rnd(r, 2, 15); add(`تمرین: حاصل (${f(a)}) + (${f(b)}) روی محور اعداد چند می‌شود؟`, `${f(a + b)}`, 'از عدد اول روی محور، به اندازهٔ عدد دوم جلو برو.'); }
      else { const l = rnd(r, 4, 18), w = rnd(r, 3, 12); add(`تمرین: مساحت مستطیلی به طول ${f(l)} و عرض ${f(w)} چقدر است؟`, `${f(l * w)} واحد مربع`, 'مساحت مستطیل = طول × عرض'); }
    } else if (grade === 7 || grade === 8) {
      if (k === 0) { const a = rnd(r, 2, 9), x = rnd(r, 2, 14); add(`تمرین: معادلهٔ x + ${f(a)} = ${f(a + x)} را حل کن.`, `x = ${f(x)}`, `از دو طرف ${f(a)} کم کن.`); }
      else if (k === 1) { const a = rnd(r, 2, 9), x = rnd(r, 2, 12); add(`تمرین: اگر ${f(a)}x = ${f(a * x)} باشد، x چند است؟`, `x = ${f(x)}`, `هر دو طرف را بر ${f(a)} تقسیم کن.`); }
      else if (k === 2) { const b = rnd(r, 2, 5), e = rnd(r, 2, 4); add(`تمرین: حاصل (${f(b)}) به توان ${f(e)} را به صورت ضرب و جواب بنویس.`, `${f(b ** e)}`, `یعنی عدد ${f(b)}، ${f(e)} بار در خودش ضرب شود.`); }
      else { const m = pick(r, [1, 2, 3]), a = 3 * m, b = 4 * m, c = 5 * m; add(`تمرین: در مثلث قائم‌الزاویه‌ای با دو ضلع قائمهٔ ${f(a)} و ${f(b)}، وتر چقدر است؟`, `${f(c)}`, `با فیثاغورس: c² = ${f(a * a)} + ${f(b * b)} = ${f(c * c)}`); }
    } else if (grade === 9) {
      if (k === 0) { const x = rnd(r, 2, 9), y = rnd(r, 1, 8); add(`تمرین: دستگاه x + y = ${f(x + y)} و x − y = ${f(x - y)} را حل کن.`, `x = ${f(x)} و y = ${f(y)}`, 'دو معادله را با هم جمع کن تا y حذف شود.'); }
      else if (k === 1) { const m = rnd(r, 1, 5), x1 = rnd(r, 0, 3), y1 = rnd(r, 0, 5), dx = rnd(r, 1, 4); add(`تمرین: شیب خط گذرنده از دو نقطهٔ (${f(x1)}،${f(y1)}) و (${f(x1 + dx)}،${f(y1 + m * dx)}) چقدر است؟`, `${f(m)}`, 'شیب = تغییرات y تقسیم بر تغییرات x'); }
      else if (k === 2) { const a = rnd(r, 2, 15), b = rnd(r, 1, 9); add(`تمرین: حاصل |${f(-a)}| + |${f(b)}| چند می‌شود؟`, `${f(a + b)}`, 'قدر مطلق یعنی فاصله از صفر؛ همیشه نامنفی.'); }
      else { const a = rnd(r, 2, 8), b = rnd(r, 2, 8); add(`تمرین: اگر A دارای ${f(a)} عضو و B دارای ${f(b)} عضو و اشتراکشان ${f(1)} عضو باشد، اجتماعشان چند عضو دارد؟`, `${f(a + b - 1)}`, 'اجتماع = |A| + |B| − |اشتراک| (عضو مشترک دو بار شمرده نشود)'); }
    } else {
      if (k === 0) { const r1 = rnd(r, 1, 6), r2 = rnd(r, r1 + 1, 9); add(`تمرین: معادلهٔ x² − ${f(r1 + r2)}x + ${f(r1 * r2)} = 0 را حل کن.`, `x = ${f(r1)} و x = ${f(r2)}`, `تجزیه: (x−${f(r1)})(x−${f(r2)}) = 0`); }
      else if (k === 1) { const e = rnd(r, 3, 7); add(`تمرین: حاصل log₂${f(2 ** e)} چقدر است؟`, `${f(e)}`, `چون ۲ به توان ${f(e)} برابر ${f(2 ** e)} است.`); }
      else if (k === 2) { const n = rnd(r, 2, 5), a = rnd(r, 2, 6); add(`تمرین: مشتق تابع f(x) = x^${f(n)} + ${f(a)}x را بنویس.`, `f′(x) = ${f(n)}x^${f(n - 1)} + ${f(a)}`, 'مشتق xⁿ برابر n·xⁿ⁻¹ و مشتق ax برابر a است.'); }
      else { const a1 = rnd(r, 2, 9), d = rnd(r, 2, 6), n = rnd(r, 5, 12); add(`تمرین: در دنبالهٔ حسابی با جملهٔ اول ${f(a1)} و قدرنسبت (اختلاف) ${f(d)}، جملهٔ ${f(n)}ام چقدر است؟`, `${f(a1 + (n - 1) * d)}`, `فرمول: aₙ = a₁ + (n−۱)d یعنی ${f(a1)} + ${f(n - 1)}×${f(d)}`); }
    }
  }
  return out;
}

