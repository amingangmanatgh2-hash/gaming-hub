function bankFor(base, grade) {
  if (base.startsWith('english')) return BANKS.english;
  if (base === 'arabic') return BANKS.arabic;
  if (base === 'farsi' || base.startsWith('farsi') || base === 'humanities10') return BANKS.farsiBank;
  if (base === 'science') return BANKS.scienceBank;
  if (base.startsWith('physics')) return BANKS.physicsBank;
  if (base.startsWith('chemistry')) return BANKS.chemBank;
  if (base.startsWith('biology')) return BANKS.bioBank;
  if (base === 'social') return BANKS.socialBank;
  if (['quran', 'hedye', 'payam', 'dini'].includes(base)) return BANKS.diniBank;
  return BANKS.studyBank;
}
const MATHY = ['math', 'math10', 'math11t', 'hesaban', 'hesaban12'];

/** روی خروجی سازنده صدا زده می‌شود و همان آرایه‌ها را کامل‌تر می‌کند. */
export function expandCatalog({ subjects, lessons }) {
  const lessonById = new Map(lessons.map((l) => [l.id, l]));
  let addedLessons = 0, addedQa = 0;

  for (const subject of subjects) {
    const grade = subject.grade;
    const base = subject.id.replace(/^g\d+-/, '');
    const mine = subject.lessons.map((id) => lessonById.get(id)).filter(Boolean);
    if (!mine.length) continue;
    const r = mulberry32(hash(subject.id));

    // ۱) تمرین محاسباتی داخل خود فصل‌های ریاضی
    if (MATHY.includes(base)) {
      for (const lesson of mine) {
        const drills = mathDrills(grade, mulberry32(hash(lesson.id)), 6);
        lesson.qa.push(...drills);
        addedQa += drills.length;
      }
    }

    // ۲) درس جمع‌بندی: مرور یک پرسش از هر فصل + همهٔ نکات کلیدی
    const reviewQa = mine.map((l, i) => {
      const originals = l.qa.filter((x) => !x.q.startsWith('تمرین:'));
      const src = originals.length ? originals : l.qa;
      return src[(hash(l.id) + i) % src.length];
    }).filter(Boolean)
      .map((item) => ({ q: 'مرور سریع: ' + item.q, a: item.a, x: item.x }));
    const allPoints = [...new Set(mine.flatMap((l) => l.points || []))].slice(0, 24);
    const nextNo = () => subject.lessons.length + 1;
    const addLesson = (title, summary, points, qa) => {
      const id = `${subject.id}-${nextNo()}`;
      const lesson = { id, subject: subject.id, grade, no: nextNo(), title, summary, points, qa };
      lessons.push(lesson); lessonById.set(id, lesson); subject.lessons.push(id);
      addedLessons++; addedQa += qa.length;
    };
    addLesson(
      'جمع‌بندی و نکات طلایی (شب امتحان)',
      `مرور سریع و یک‌جای همهٔ فصل‌های ${subject.title}: اول نکات طلایی را بخوان، بعد با پرسش‌های مرور خودت را محک بزن. برای شب امتحان دقیقاً همین فصل را لازم داری!`,
      allPoints.length ? allPoints : ['خلاصهٔ هر فصل را یک بار با صدای بلند برای خودت توضیح بده.'],
      reviewQa,
    );

    // ۳) درس تمرین و نمونه‌سوال بیشتر
    const extraQa = MATHY.includes(base)
      ? mathDrills(grade, r, 12)
      : bankFor(base, grade).map(([q, a, x]) => ({ q, a, x: x || '' }));
    addLesson(
      'تمرین و نمونه‌سوال بیشتر',
      `بانک تمرین تکمیلی درس ${subject.title} برای تثبیت یادگیری: اول روی کاغذ حل کن، بعد جواب را باز کن و راه‌حل را با کار خودت مقایسه کن.`,
      ['اول خودت حل کن، بعد جواب را ببین؛ قانون طلایی یادگیری!', 'هر جا اشتباه کردی، همان نکته را در دفترت بنویس و فردا دوباره حلش کن.'],
      extraQa,
    );
  }
  return { addedLessons, addedQa };
}
